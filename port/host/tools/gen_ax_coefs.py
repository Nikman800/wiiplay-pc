"""Generate port/host/src/host_ax_coefs.h: the AX 4-tap polyphase SRC tables
that are not in the decomp (port/docs/HOST_BUILD.md §21).

The DSP's sample-rate converter reads 4-tap, 128-phase coefficient tables from
its coefficient ROM: coefSelect 0 (8 kHz cutoff), 1 (12 kHz), 2 (16 kHz). The
12 kHz table is in the decomp as floats (src/revolution/AXFX/AXFXSrcCoef.c,
which AXFX's chorus uses on the CPU); multiplied by 32768 it gives the ROM's
s16 values exactly, and host_ax.cpp builds that table from it at start-up.

The 8 kHz and 16 kHz tables are not in the decomp. They are generated the way
Dolphin's free DSP ROM replacement generates its coefficient table
(docs/DSP/free_dsp_rom/generate_coefs.py in Dolphin, described there as an
approximation): a 512-point windowed sinc over x in [-2, 2] (sinc(c*x) times
a Hamming window, c = 0.5 for 8 kHz and 1.0 for 16 kHz), split into four
128-point blocks, each reversed; row i of the table is (block0[127-i],
block1[127-i], block2[127-i], block3[127-i]) (tap order: oldest sample
first), scaled so the largest row sum is 32767, rounded half to even.
The same construction with a Kaiser window (beta = 9*pi/4, c = 0.75) gives
the 12 kHz table within 19/32768 of the real one, so the generated 8/16 kHz
tables are approximations of the same order.

    python3 port/host/tools/gen_ax_coefs.py            # rewrite the header
    python3 port/host/tools/gen_ax_coefs.py --check    # exit 1 if it differs
"""

import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(HERE, "..", "src", "host_ax_coefs.h")
N = 512


def _sinc(u):
    return 1.0 if u == 0 else math.sin(math.pi * u) / (math.pi * u)


def _hamming(n):
    return 0.54 - 0.46 * math.cos(2 * math.pi * n / (N - 1))


def _convert(c):
    rows = [(c[127 - i], c[255 - i], c[383 - i], c[511 - i]) for i in range(128)]
    m = max(sum(r) for r in rows)
    return [[int(round(v / m * 32767)) for v in r] for r in rows]


def generated_table(cutoff):
    """128 rows of 4 s16 taps for a Hamming-windowed sinc with this cutoff."""
    x = [-2 + 4 * n / (N - 1) for n in range(N)]
    return _convert([_sinc(cutoff * x[n]) * _hamming(n) for n in range(N)])


def decomp_12k_table(repo):
    """The 12 kHz table from the decomp's AXFXSrcCoef.c, as s16."""
    src = open(os.path.join(repo, "src", "revolution", "AXFX", "AXFXSrcCoef.c")).read()
    vals = [float(v) for v in re.findall(r"(-?\d+\.\d+)f", src)]
    assert len(vals) == 512, len(vals)
    out = []
    for i in range(128):
        row = []
        for k in range(4):
            q = vals[4 * i + k] * 32768
            assert abs(q - round(q)) < 1e-3
            row.append(int(round(q)))
        out.append(row)
    return out


def tables(repo):
    """The three tables host_ax.cpp uses, indexed by coefSelect."""
    return [generated_table(0.5), decomp_12k_table(repo), generated_table(1.0)]


def render():
    out = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "// Generated by port/host/tools/gen_ax_coefs.py (GPL-2.0-or-later: its construction",
        "// follows the Dolphin emulator's free DSP ROM, Copyright 2008 Dolphin Emulator",
        "// Project; LICENSES/GPL-2.0-or-later.txt). Unlike the rest of this repository (CC0).",
        "",
        "/* Generated by port/host/tools/gen_ax_coefs.py; do not edit.",
        " * AX polyphase SRC tables not in the decomp (HOST_BUILD.md §21):",
        " * coefSelect 0 (8 kHz) and 2 (16 kHz), 128 phases x 4 taps, oldest",
        " * sample first. Generated like Dolphin's free DSP ROM table (an",
        " * approximation of the real ROM); coefSelect 1 comes from the decomp. */",
        "",
        "#ifndef PORT_HOST_AX_COEFS_H",
        "#define PORT_HOST_AX_COEFS_H",
        "",
    ]
    for name, cutoff in (("sAxSrcCoef8k", 0.5), ("sAxSrcCoef16k", 1.0)):
        out.append("static const s16 %s[128][4] = {" % name)
        for r in generated_table(cutoff):
            out.append("    {%s}," % ", ".join("%d" % v for v in r))
        out.append("};")
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        cur = open(HEADER).read() if os.path.exists(HEADER) else ""
        if cur != text:
            print("gen_ax_coefs: %s is out of date" % HEADER)
            return 1
        print("gen_ax_coefs: OK")
        return 0
    with open(HEADER, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
